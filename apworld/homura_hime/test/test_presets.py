"""
The option presets of the options page: each is made of options that exist and values the website accepts (the rules of
Archipelago's own preset tests), Standard is the defaults, and every preset generates (the random ones with several
rolls).
"""
import os
import random
import unittest

from Options import NamedRange, NumericOption, PerGameCommonOptions, Range

from .. import HomuraHimeWorld
from ..options import HomuraHimeOptions
from ..presets import STANDARD, options_presets
from . import test_generation  # the base class is used through the module so that pytest does not collect it here again
from .test_shop_budget import generate

# how many rolls of each random preset are generated by test_random_presets_generate (HH_PRESET_ROLLS for a longer run)
ROLLS = int(os.environ.get("HH_PRESET_ROLLS", "40"))

GAME_OPTIONS = set(HomuraHimeOptions.type_hints) - set(
    PerGameCommonOptions.__dataclass_fields__
)  # the options of this game


def roll(preset: dict, rng: random.Random) -> dict:
    """The preset with every "random" replaced by a value of the option, the way a player's yaml would be rolled."""
    options = {}
    for name, value in preset.items():
        option = HomuraHimeOptions.type_hints[name]
        if value != "random":
            options[name] = value
        elif issubclass(option, Range):
            options[name] = rng.randint(option.range_start, option.range_end)
        else:
            options[name] = rng.choice([False, True])
    return options


class TestPresetDefinitions(unittest.TestCase):
    def test_there_are_the_three_presets(self):
        self.assertEqual(["Standard", "Balanced Random", "Chaos"], list(options_presets))
        self.assertIs(options_presets, HomuraHimeWorld.web.options_presets)

    def test_every_preset_is_made_of_options_and_values_the_website_accepts(self):
        for preset_name, preset in options_presets.items():
            for name, value in preset.items():
                with self.subTest(preset=preset_name, option=name):
                    self.assertIn(name, HomuraHimeOptions.type_hints, "not an option of the world")
                    option = HomuraHimeOptions.type_hints[name].from_any(value)
                    self.assertIsInstance(option, NumericOption)
                    self.assertFalse(
                        str(value).startswith("random-"), "special random values are not supported for presets"
                    )
                    if isinstance(value, str) and value != "random":
                        if isinstance(option, NamedRange):
                            self.assertIn(value, option.special_range_names)
                        else:  # no alias, and nothing that from_text resolves to another value
                            self.assertEqual(value, option.name_lookup.get(option.value))

    def test_every_preset_sets_every_option_of_the_game(self):
        for preset_name, preset in options_presets.items():
            with self.subTest(preset=preset_name):
                self.assertEqual(
                    GAME_OPTIONS, set(preset), "a preset that leaves an option out keeps whatever was chosen before"
                )

    def test_standard_is_the_defaults(self):
        for name, value in STANDARD.items():
            with self.subTest(option=name):
                self.assertEqual(
                    HomuraHimeOptions.type_hints[name].default, HomuraHimeOptions.type_hints[name].from_any(value).value
                )

    def test_the_bug_report_page_is_set(self):
        self.assertTrue(HomuraHimeWorld.web.bug_report_page.startswith("https://github.com/"))


