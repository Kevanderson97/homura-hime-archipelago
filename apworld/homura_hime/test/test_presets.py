class TestRandomPresetsGenerate(unittest.TestCase):
    """The presets that roll their values (every Chaos option is random) generate for many rolls, alone and with a
    friend."""

    def test_random_presets_generate(self):
        for preset in ("Chaos", "Balanced Random"):
            for players in (1, 2):
                for roll_seed in range(1, ROLLS // players + 1):
                    options = roll(options_presets[preset], random.Random(roll_seed))
                    with self.subTest(preset=preset, players=players, roll=roll_seed):
                        generate(roll_seed, options, players)  # the shop budget check runs as well
