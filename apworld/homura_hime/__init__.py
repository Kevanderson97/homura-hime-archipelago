"""Homura-Hime Archipelago world.

Data (locations, items, regions) is generated by tools/build_data.py and shared with the BepInEx plugin; see
apworld/README.md for the design and the logic in detail.

Logic in short:
- Worlds (the eight chapters and the climax) are entered in play order (vanilla or randomized), optionally behind unlock
  items; the climax is never the first world and needs a cleared chapter; the finale needs all of them.
- Key items gate parts of chapters (SCENE_REQ, TRANSITION_REQ); Level 1 also needs a dash skill (unless the option
  advanced_movement_required asks the player to parry the laser across the gap instead).
- Shop slots need their tier of cleared chapters, enough Konpeito (1.5 times the Konpeito paid out by the
  randomizer, MONEY_FACTOR) and the Senbei they cost (some slots charge Senbei too; those cannot be farmed, so the
  logic counts exactly the Senbei received). Shop slots never hold this world's own Konpeito (a wasted purchase).
  What a finished seed makes everybody buy in the shops is checked against that budget in shop_budget.py.
- Harumi needs a cleared chapter (HARUMI_MIN_CLEARED) and Sakura Petals: PETALS_PER_CHAPTER for every cleared chapter plus the
  Sakura items held.
The large Konpeito and Sakura items are progression for the generator (only advancement items are counted by the
logic) and stand for all of that currency in the pool (COUNTED_KONPEITO_MIN); clients see every currency item as filler
(HomuraHimeItem.flags).
"""
