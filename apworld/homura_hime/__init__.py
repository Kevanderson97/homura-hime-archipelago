class HomuraHimeWorld(World):
    """Homura-Hime is an action game about a fire-wielding exorcist crossing the demon-haunted lands, scored by rank
    and tuned around parries, combos and Blessed Shots."""

    game = GAME_NAME
    web = HomuraHimeWebWorld()
    options_dataclass = HomuraHimeOptions
    options: HomuraHimeOptions
    topology_present = True
    required_client_version = (0, 5, 0)

    item_name_to_id = ITEM_NAME_TO_ID
    location_name_to_id = LOCATION_NAME_TO_ID
    item_name_groups = {
        "Key Items": set(GATE_ITEMS),
        "Dash Skills": set(DASH_SKILLS),
        "Chapter Unlocks": {i["name"] for i in ITEMS if i["type"] == "unlock"},
        "Guns": {i["name"] for i in ITEMS if i["type"] == "gun"},
        "Omamori": {i["name"] for i in ITEMS if i["type"] == "omamori"},
    }
    location_name_groups = {
        label: {loc["name"] for loc in LOCATIONS if loc["category"] in categories}
        for label, categories in LOCATION_GROUPS.items()
    }

    order: List[str]
    active_locations: List[dict]
    shop_slots: List[HomuraHimeShopLocation]
    start_dash: str = ""
    # whether the logic asks for a dash skill (not with advanced_movement_required); item link groups keep this
    dash_required: bool = True
    chapter_number: Dict[str, int]
    # all Konpeito / Sakura / Senbei of the pool per counted unit (see COUNTED_KONPEITO_MIN), set by create_items
    money_scale: float = 1.0
    petal_scale: float = 1.0
    senbei_scale: float = 1.0
    # the one Senbei item that counts for the logic: the "2 Senbei" pieces when the pool has them, else "Senbei"
    senbei_unit: str = "2 Senbei"

    # ------------------------------------------------------------------ generation
    def generate_early(self) -> None:
        """Decides the chapter order and the starting items before the item pool and the regions are built."""
        self.shop_slots = []
        self.chapter_number = {c["id"]: c["number"] for c in CHAPTERS}
        self.order = [c["id"] for c in CHAPTERS]
        passthrough: Optional[Dict[str, Any]] = getattr(self.multiworld, "re_gen_passthrough", {}).get(GAME_NAME)
        if passthrough:
            self._apply_passthrough(passthrough)
        elif self.options.level_order == self.options.level_order.option_randomized:
            self.random.shuffle(self.order)
        self.active_locations = self._active_locations()

        self.dash_required = not self.options.advanced_movement_required
        if self.options.dash_skill_start:
            if not self.start_dash:
                self.start_dash = self.random.choice(DASH_SKILLS)
            self.multiworld.push_precollected(self.create_item(self.start_dash))
        elif self.dash_required:
            # Level 1 needs a dash skill from its second area on (the rules enforce it). Guarantee that one is
            # obtainable early, either in this world or as an early item sent from another world.
            self.multiworld.early_items[self.player][self.random.choice(DASH_SKILLS)] = 1
        if self.options.level_unlock_items:
            # the first chapter in play order is always open
            self.multiworld.push_precollected(self.create_item(f"Chapter {self.chapter_number[self.order[0]]} Unlock"))

    def _apply_passthrough(self, slot_data: Dict[str, Any]) -> None:
        """Universal Tracker regenerates the world from the slot data: the same chapter order, start and options."""
        self.order = list(slot_data["level_order"])
        self.start_dash = slot_data["start_dash_skill"]
        self.options.level_order.value = self.options.level_order.options[slot_data["level_order_mode"]]
        self.options.dash_skill_start.value = int(bool(self.start_dash))
        for name in SLOT_DATA_TOGGLES:
            getattr(self.options, name).value = int(slot_data.get(name, 0))

    @staticmethod
    def interpret_slot_data(slot_data: Dict[str, Any]) -> Dict[str, Any]:
        """Universal Tracker: the slot data is all that is needed to regenerate the world (see _apply_passthrough)."""
        return slot_data

    def _active_locations(self) -> List[dict]:
        """The location records in play: the optional encounter locations only exist when their option is on."""
        return [loc for loc in LOCATIONS
                if not (loc.get("option") == "encounter_rewards" and not self.options.encounter_rewards)
                and not (loc.get("option") == "encounter_clears" and not self.options.encounter_clears)]

    def create_item(self, name: str) -> HomuraHimeItem:
        """Creates an item of this world; the classification depends on the options (see the comments below)."""
        if self._counted(name):
            # the large currency pieces count as progression (the shop prices and Harumi depend on them), never
            # balanced forward
            classification = ItemClassification.progression_skip_balancing
        elif name in DASH_SKILLS and not self.dash_required:
            classification = ItemClassification.useful  # nothing needs them
        else:
            classification = CLASSIFICATION[ITEM_BY_NAME[name]["classification"]]
        return HomuraHimeItem(name, classification, ITEM_BY_NAME[name]["id"], self.player)

    def get_filler_item_name(self) -> str:
        return "Full Heal"  # a real filler item: the currency items count in the logic

    def _vanilla_placements(self) -> Dict[str, str]:
        """
        Location key -> item name for the groups that are not shuffled: each item goes to the first location whose
        base-game reward it is (a location holds one item, so a location that pays a bundle keeps the first item of an
        unshuffled group in it; an item whose locations are all taken stays in the pool). Only as many copies are placed
        as the pool holds.
        """
        item_types = {item_type for option, group in SHUFFLE_GROUPS.items()
                      if not getattr(self.options, option) for item_type in group}
        if not item_types:
            return {}
        by_definition = {i["game"]: i for i in ITEMS if i["type"] in item_types and not i.get("option")}
        remaining = {i["name"]: i["count"] for i in by_definition.values()}
        placed: Dict[str, str] = {}
        for loc in self.active_locations:
            for part in (loc.get("vanilla") or "").split(";"):
                item = by_definition.get(re.sub(r"\s+x\d+$", "", part.strip()))
                if item is not None and remaining[item["name"]] > 0:
                    placed[loc["key"]] = item["name"]
                    remaining[item["name"]] -= 1
                    break
        return placed

    def create_items(self) -> None:
        """
        Builds the item pool: the fixed items of the game, the Konpeito the base game pays at its locations, the
        Senbei, and currency/utility filler for the locations that remain. Groups that are not shuffled are placed
        at their vanilla locations first.
        """
        locked = self._vanilla_placements()
        for key, item_name in locked.items():
            self.get_location(NAME_OF_KEY[key]).place_locked_item(self.create_item(item_name))
        pool: List[str] = []
        for item in ITEMS:
            if item["classification"] == "filler" or item["type"] == "unlock":
                continue
            if item.get("option") == "cut_content" and not self.options.include_cut_content:
                continue
            pool += [item["name"]] * item["count"]
        for item_name in locked.values():
            if item_name in pool:
                pool.remove(item_name)
        if self.start_dash:
            pool.remove(self.start_dash)
        if self.options.level_unlock_items:
            pool += [f"Chapter {n} Unlock" for n in self.chapter_number.values()
                     if n != self.chapter_number[self.order[0]]]
        pool += ["Special Hanami Dango"] * self.options.dango_count.value
        # the Konpeito the vanilla game pays at its locations (the plugin takes those payouts away): one item each
        fixed_konpeito = [loc["konpeito"] for loc in self.active_locations if "konpeito" in loc]
        pool += [f"{amount} Konpeito" for amount in fixed_konpeito]

        free = len(self.active_locations) - len(locked) - len(pool)
        if free < 0:
            raise OptionError(f"Homura-Hime ({self.player_name}): {len(pool)} items for "
                              f"{len(self.active_locations) - len(locked)} free locations")
        # the Senbei total is handed out as single Senbei and, above SENBEI_PIECES, as "2 Senbei" items
        total = self.options.senbei_count.value
        pieces = min(total, SENBEI_PIECES, free)
        pairs = min(max(0, total - pieces), pieces)
        pool += ["Senbei"] * (pieces - pairs) + ["2 Senbei"] * pairs
        free -= pieces
        pool += self._currency_filler(free, sum(fixed_konpeito))
        self.senbei_unit = "2 Senbei" if "2 Senbei" in pool else "Senbei"
        self.money_scale = self._scale_currency(pool, KONPEITO_VALUES, COUNTED_KONPEITO)
        self.petal_scale = self._scale_currency(pool, SAKURA_VALUES, COUNTED_SAKURA)
        self.senbei_scale = self._scale_currency(pool, SENBEI_VALUES, self._counted_senbei())
        self.multiworld.itempool += [self.create_item(name) for name in pool]

    @staticmethod
    def _scale_currency(pool: List[str], values: Dict[str, int], counted: Dict[str, int]) -> float:
        """All of a currency in the pool per unit of its counted pieces (1 when nothing of it is counted)."""
        total = sum(values.get(name, 0) for name in pool)
        counted_total = sum(counted.get(name, 0) for name in pool)
        return total / counted_total if counted_total else 1.0

    def _currency_filler(self, free: int, fixed_konpeito: int) -> List[str]:
        """
        Fills the remaining slots: the Full Heal and Ultimate Charge items, then Sakura Petals and Konpeito.
        - The counted Sakura items hold at least MIN_SAKURA_IN_POOL (Harumi's last reward needs them), taken from
          Konpeito slots.
        - The Konpeito pieces are raised in size until the pool holds at least options.minimum_konpeito in total (the
          fixed vanilla payouts count towards it); if every piece is at the largest size and it is still short, Sakura
          slots the Harumi minimum can spare and then utility slots turn into Konpeito.
        """
        utility = ["Full Heal"] * self.options.full_heal_count.value
        utility += ["Ultimate Charge"] * self.options.ultimate_charge_count.value
        slots: List[Optional[str]] = utility[:free]  # None = a Konpeito slot, its size is decided below
        for _ in range(free - len(slots)):
            if self.random.randrange(100) < self.options.filler_sakura_ratio.value:
                slots.append(self.random.choices(SAKURA_ITEMS, SAKURA_WEIGHTS)[0])
            else:
                slots.append(None)

        def sakura() -> int:
            return sum(COUNTED_SAKURA.get(slot, 0) for slot in slots)

        largest_sakura = SAKURA_ITEMS[-1]
        while sakura() < MIN_SAKURA_IN_POOL:
            spare = [i for i, slot in enumerate(slots) if slot is None] or \
                    [i for i, slot in enumerate(slots) if slot not in SAKURA_VALUES] or \
                    [i for i, slot in enumerate(slots) if slot != largest_sakura]
            if not spare:
                raise OptionError(f"Homura-Hime ({self.player_name}): no room for the Sakura Harumi needs")
            slots[self.random.choice(spare)] = largest_sakura

        amounts = {i: KONPEITO_VALUES[self.random.choices(KONPEITO_ITEMS, KONPEITO_WEIGHTS)[0]]
                   for i, slot in enumerate(slots) if slot is None}
        missing = self.options.minimum_konpeito.value - fixed_konpeito - sum(amounts.values())
        largest = KONPEITO_LADDER[-1]
        while missing > 0:
            raisable = [i for i, amount in amounts.items() if amount < largest]
            if not raisable:
                # Sakura slots the Harumi minimum can spare go first, the Full Heal / Ultimate Charge counts the player
                # asked for only when nothing else is left
                surplus = sakura() - MIN_SAKURA_IN_POOL
                others = [i for i, slot in enumerate(slots) if COUNTED_SAKURA.get(slot, 0) <= surplus
                          and slot in SAKURA_VALUES] \
                    or [i for i, slot in enumerate(slots) if slot is not None and slot not in SAKURA_VALUES]
                if not others:
                    break  # every slot is a maximal Konpeito piece or needed Sakura: the minimum cannot be reached
                i = self.random.choice(others)
                slots[i], amounts[i] = None, 0
                raisable = [i]
            i = self.random.choice(raisable)
            higher = KONPEITO_LADDER[KONPEITO_LADDER.index(amounts[i]) + 1] if amounts[i] else KONPEITO_LADDER[0]
            missing -= higher - amounts[i]
            amounts[i] = higher
        if missing > 0:
            logging.warning("Homura-Hime (%s): the pool has room for about %d fewer Konpeito than minimum_konpeito "
                            "asks for", self.player_name, missing)
        return [slot if slot is not None else f"{amounts[i]} Konpeito" for i, slot in enumerate(slots)]

    # ------------------------------------------------------------------ counted items
    def _counted_senbei(self) -> Dict[str, int]:
        """The Senbei item the logic counts (see senbei_unit) and its value."""
        return {self.senbei_unit: SENBEI_VALUES[self.senbei_unit]}

    def _counted(self, name: str) -> Optional[Tuple[str, int]]:
        """The running total an item adds to and by how much, or None when the logic does not count it."""
        if name in self._counted_senbei():
            return SENBEI_COUNTER, SENBEI_VALUES[name]
        return COUNTED.get(name)

    def collect(self, state, item: Item) -> bool:
        """Collecting a counted item also adds its value to the running total it belongs to."""
        changed = super().collect(state, item)
        counted = self._counted(item.name) if changed else None
        if counted:
            state.add_item(counted[0], self.player, counted[1])
        return changed

    def remove(self, state, item: Item) -> bool:
        """The reverse of collect: the value of a counted item leaves its running total."""
        changed = super().remove(state, item)
        counted = self._counted(item.name) if changed else None
        if counted:
            state.remove_item(counted[0], self.player, counted[1])
        return changed

    def _money(self, state) -> int:
        """
        What the player can reasonably have spent by now: MONEY_FACTOR times the Konpeito the randomizer paid out, as
        the counted pieces held stand for it.
        """
        return int(MONEY_FACTOR * self.money_scale * state.count(MONEY_COUNTER, self.player))

    def _senbei(self, state) -> int:
        """
        The Senbei received, as the counted pieces stand for it. Not multiplied by anything: the game has no other
        source of Senbei than the locations, so every Senbei the shops cost has to come from items.
        """
        return int(self.senbei_scale * state.count(SENBEI_COUNTER, self.player))

    def _petals(self, state) -> int:
        """The Sakura the logic counts on: PETALS_PER_CHAPTER for every cleared chapter plus the Sakura items held."""
        return PETALS_PER_CHAPTER * state.count(CLEARED_COUNTER, self.player) + \
            int(self.petal_scale * state.count(PETAL_COUNTER, self.player))

    def _cleared(self, state) -> int:
        """The number of chapters cleared in this state."""
        return state.count(CLEARED_COUNTER, self.player)

    @classmethod
    def stage_finalize_multiworld(cls, multiworld) -> None:
        """
        Once every item is placed and progression balancing is done (it can still move items after post_fill): the
        progression bought in the shops must be affordable by the time it is needed. The repair only moves needed items
        earlier, which is what this stage allows (accessibility may only increase).
        """
        worlds = multiworld.get_game_worlds(GAME_NAME)  # item link groups are not included
        if worlds:
            shop_budget.enforce(multiworld, worlds)

    # ------------------------------------------------------------------ regions
    def create_regions(self) -> None:
        """
        Menu -> Hub -> the sub-chapters of each chapter in story order (chained), plus the finale. Chapter regions are
        entered from the hub; a chapter's first region carries the "Chapter N Entered" event and its last the
        "Chapter N Cleared" event, the finale's last region the "Victory" event.
        """
        menu = Region("Menu", self.player, self.multiworld)
        hub = Region("Hub", self.player, self.multiworld)
        self.multiworld.regions += [menu, hub]
        menu.connect(hub, "Start")

        regions: Dict[str, Region] = {"Hub": hub}
        for chapter in CHAPTERS + [FINALE]:
            for sub in chapter["sub_chapters"]:
                regions[sub["key"]] = Region(sub["key"], self.player, self.multiworld)
                self.multiworld.regions.append(regions[sub["key"]])

        for chapter in CHAPTERS:
            cid = chapter["id"]
            subs = chapter["sub_chapters"]
            hub.connect(regions[subs[0]["key"]], f"Enter {cid}", lambda state, cid=cid: self._can_enter(state, cid))
            for a, b in zip(subs, subs[1:]):
                reqs = TRANSITION_REQ.get(a["key"], [])
                regions[a["key"]].connect(regions[b["key"]], f"{a['key']} -> {b['key']}",
                                          (lambda state, reqs=reqs: self._req(state, reqs)) if reqs else None)
            self._event(regions[subs[0]["key"]], f"Chapter {chapter['number']} Entered")
            self._event(regions[subs[-1]["key"]], f"Chapter {chapter['number']} Cleared")

        finale = FINALE["sub_chapters"]
        hub.connect(regions[finale[0]["key"]], "Enter Finale", lambda state: self._cleared(state) >= len(CHAPTERS))
        for a, b in zip(finale, finale[1:]):
            regions[a["key"]].connect(regions[b["key"]], f"{a['key']} -> {b['key']}")
        self._event(regions[finale[-1]["key"]], "Victory")

        for loc in self.active_locations:
            region = regions[loc["region"]]
            if loc["category"] == "shop":
                location = HomuraHimeShopLocation(self.player, loc["name"], loc["id"], region)
                location.price, location.senbei = SHOP_PRICES[loc["key"]], SHOP_SENBEI[loc["key"]]
                self.shop_slots.append(location)
            else:
                location = HomuraHimeLocation(self.player, loc["name"], loc["id"], region)
            region.locations.append(location)
            self._apply_optional_importance(location, loc)

    def _event(self, region: Region, name: str) -> None:
        """Adds a locked event item with a matching event location to a region (the logic's progress markers)."""
        location = HomuraHimeLocation(self.player, name, None, region)
        region.locations.append(location)
        location.place_locked_item(HomuraHimeItem(name, ItemClassification.progression, None, self.player))

    def _apply_optional_importance(self, location: HomuraHimeLocation, loc: dict) -> None:
        """Optional content (ambushes, trials, head chases, Ikai rooms) hides important items less often: only a share
        of those locations may hold progression or useful items, the rest are excluded from them."""
        if loc["category"] not in OPTIONAL_CATEGORIES and not loc.get("optional"):
            return
        if self.random.randrange(100) >= self.options.optional_location_importance.value:
            location.progress_type = LocationProgressType.EXCLUDED

    # ------------------------------------------------------------------ rules
    def _req(self, state, reqs: List[str]) -> bool:
        """Whether the state has every requirement; "dash" stands for any dash skill (see SCENE_REQ)."""
        for r in reqs:
            if r == "dash":
                if self.dash_required and not state.has_any(DASH_SKILLS, self.player):
                    return False
            elif not state.has(r, self.player):
                return False
        return True

    def _can_enter(self, state, chapter_id: str) -> bool:
        """
        Whether a chapter can be entered from the hub: in play order the previous chapter must be cleared (except with
        randomized order and unlock items, where the unlock item alone opens a chapter), and with unlock items the
        chapter's own unlock item is needed.
        """
        slot = self.order.index(chapter_id)
        needs_previous = slot > 0 and not (self.options.level_unlock_items
                                           and self.options.level_order == self.options.level_order.option_randomized)
        previous = self.chapter_number[self.order[slot - 1]]
        if needs_previous and not state.has(f"Chapter {previous} Cleared", self.player):
            return False
        if self.options.level_unlock_items and not state.has(f"Chapter {self.chapter_number[chapter_id]} Unlock",
                                                             self.player):
            return False
        return True

    def set_rules(self) -> None:
        """Applies the access rule of every location and the completion condition (the finale's Victory event)."""
        for loc in self.active_locations:
            self._apply_location_rules(self.get_location(loc["name"]), loc)
        self.multiworld.completion_condition[self.player] = lambda state: state.has("Victory", self.player)

    def _apply_location_rules(self, location: Location, loc: dict) -> None:
        """The access rule and item rules of one location, built from its category and the requirement tables."""
        reqs: List[str] = list(loc["scene_req"] if "scene_req" in loc else SCENE_REQ.get(loc.get("scene", ""), []))
        category = loc["category"]
        rule: Optional[Callable] = None
        if category == "shop":
            # the tier of the slot in cleared chapters, and the price in Konpeito and Senbei
            tier, price, senbei = max(loc["tier"], SHOP_MIN_CLEARED), loc["price"], loc["senbei"]
            rule = lambda state, tier=tier, price=price, senbei=senbei: \
                self._cleared(state) >= tier and self._money(state) >= price and self._senbei(state) >= senbei
            if self.dash_required:
                # a dash skill is needed early in Level 1; shop prices (8000+ Konpeito) would make that a grind
                add_item_rule(location, lambda item: not (item.player == self.player and item.name in DASH_SKILLS))
            # the shop is paid for with Konpeito, so selling it there is a wasted purchase (Senbei may be sold: they are
            # scarce, and the budget check counts them when they sit in a slot)
            add_item_rule(location, lambda item: not (item.player == self.player and item.name in KONPEITO_VALUES))
        elif category == "stage_clear":
            number = self.chapter_number[loc["chapter"]]
            rule = lambda state, number=number: state.has(f"Chapter {number} Cleared", self.player)
        elif category == "harumi":
            rule = lambda state, need=loc["petals"]: \
                self._cleared(state) >= HARUMI_MIN_CLEARED and self._petals(state) >= need
        elif loc["key"] in HUB_CLEARS_REQUIRED:
            rule = lambda state, clears=HUB_CLEARS_REQUIRED[loc["key"]]: self._cleared(state) >= clears
        elif category == "stall":
            reqs.append("Inugami Certificate")
        if reqs:
            base = rule
            rule = lambda state, reqs=reqs, base=base: self._req(state, reqs) and (base is None or base(state))
        if rule is not None:
            set_rule(location, rule)

        # gate items may not go where we cannot yet tell front from behind the gate
        scene = loc.get("scene")
        for item_name, (gate_scene, safe_key) in GATE_PLACEMENT_LIMIT.items():
            if scene == gate_scene and loc["key"] != safe_key:
                add_item_rule(location, lambda item, item_name=item_name:
                              not (item.player == self.player and item.name == item_name))

    # ------------------------------------------------------------------ slot data
    def fill_slot_data(self) -> Dict[str, Any]:
        """What the plugin (and Universal Tracker) need to know about this slot beyond the item and location tables."""
        return {
            "world_version": self.world_version.as_simple_string(),
            "level_order": self.order,
            "level_order_mode": self.options.level_order.current_key,
            "start_dash_skill": self.start_dash,
            "dango_count": self.options.dango_count.value,
            **{name: bool(getattr(self.options, name)) for name in SLOT_DATA_TOGGLES},
        }
