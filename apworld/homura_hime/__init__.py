    # ------------------------------------------------------------------ generation
    def generate_early(self) -> None:
        """Decides the chapter order and the starting items before the item pool and the regions are built."""
        self.shop_slots = []
        self.order = [c["id"] for c in CHAPTERS]
        passthrough: Optional[Dict[str, Any]] = getattr(self.multiworld, "re_gen_passthrough", {}).get(GAME_NAME)
        if passthrough:
            self._apply_passthrough(passthrough)
        elif self.options.level_order == self.options.level_order.option_full:
            self.random.shuffle(self.order)
            if self.order[0] == CLIMAX_ID:
                # the climax is never the first world: it trades places with any other one
                swap = self.random.randrange(1, len(self.order))
                self.order[0], self.order[swap] = self.order[swap], self.order[0]
        elif self.options.level_order == self.options.level_order.option_balanced:
            self.order = self._balanced_order()
        self.active_locations = self._active_locations()
        self._drop_unshuffled_non_local()

        self.dash_required = not self.options.advanced_movement_required
        if self.dash_required:
            # Level 1 needs a dash skill from its second area on (the rules enforce it). Guarantee that one is
            # obtainable early, either in this world or as an early item sent from another world.
            self.multiworld.early_items[self.player][self.random.choice(DASH_SKILLS)] = 1
        # the first world in play order is always open
        if self.options.level_unlock_items == self.options.level_unlock_items.option_freeform_progression:
            self.multiworld.push_precollected(self.create_item(f"{LABEL_OF[self.order[0]]} Unlock"))
        elif self.options.level_unlock_items == self.options.level_unlock_items.option_linear_progression:
            self.multiworld.push_precollected(self.create_item(PROGRESSIVE_KEY))

    def _balanced_order(self) -> List[str]:
        """
        level_order: balanced. The first world is one of Chapters 1-4, the second is one of them with a 66% chance, the third
        with a 40% chance, each of the last three is one of Chapters 5-8 or the Climax with a 60% chance (see BALANCED_*_DRAW).
        The Climax is therefore never first. First the kind of the six constrained places is drawn (again when it needs more
        worlds of a kind than exist), then the worlds of each kind are put in at random, and the three in the middle take the
        rest.
        """
        worlds = [c["id"] for c in CHAPTERS]
        early = [w for w in worlds if w in EARLY_WORLDS]
        late = [w for w in worlds if w not in EARLY_WORLDS]
        while True:
            kinds = (["early"]
                     + ["early" if self.random.random() < chance else "late" for chance in (BALANCED_SECOND_DRAW, BALANCED_THIRD_DRAW)]
                     + [None] * 3
                     + ["late" if self.random.random() < BALANCED_LATE_DRAW else "early" for _ in range(3)])
            if kinds.count("early") <= len(early) and kinds.count("late") <= len(late):
                break
        self.random.shuffle(early)
        self.random.shuffle(late)
        order = [early.pop() if kind == "early" else late.pop() if kind == "late" else None for kind in kinds]
        rest = early + late
        self.random.shuffle(rest)
        return [world if world is not None else rest.pop() for world in order]

    def _drop_unshuffled_non_local(self) -> None:
        """
        A group that is not shuffled keeps its items at their vanilla places in this world, so those items cannot be
        non-local: the request is dropped (with a note in the generation log) instead of being silently broken.
        """
        unshuffled = {item_type for option, group in SHUFFLE_GROUPS.items()
                      if not getattr(self.options, option) for item_type in group}
        dropped = self.options.non_local_items.value & {i["name"] for i in ITEMS if i["type"] in unshuffled}
        if dropped:
            self.options.non_local_items.value -= dropped
            logging.warning("Homura-Hime (%s): %d non_local_items are not shuffled (shuffle_* is off), they stay in this world",
                            self.player_name, len(dropped))

    def _apply_passthrough(self, slot_data: Dict[str, Any]) -> None:
        """Universal Tracker regenerates the world from the slot data: the same chapter order and options."""
        self.order = list(slot_data["level_order"])
        self.options.level_order.value = self.options.level_order.options[slot_data["level_order_mode"]]
        self.options.level_unlock_items.value = self.options.level_unlock_items.options[slot_data["level_unlock_items"]]
        for name in SLOT_DATA_TOGGLES:
            getattr(self.options, name).value = int(slot_data.get(name, 0))

    @staticmethod
    def interpret_slot_data(slot_data: Dict[str, Any]) -> Dict[str, Any]:
        """Universal Tracker: the slot data is all that is needed to regenerate the world (see _apply_passthrough)."""
        return slot_data

    def _active_locations(self) -> List[dict]:
        """The location records in play: the optional encounter locations only exist when their option is on."""
        return [loc for loc in LOCATIONS
                if not (loc.get("option") == "encounter_rewards" and not self.options.encounter_rewards)
                and not (loc.get("option") == "encounter_clears" and not self.options.encounter_clears)]

    def create_item(self, name: str) -> HomuraHimeItem:
        """Creates an item of this world; the classification depends on the options (see the comments below)."""
        if self._counted(name):
            # the large currency pieces count as progression (the shop prices and Harumi depend on them), never
            # balanced forward
            classification = ItemClassification.progression_skip_balancing
        elif name in DASH_SKILLS and not self.dash_required:
            classification = ItemClassification.useful  # nothing needs them
        else:
            classification = CLASSIFICATION[ITEM_BY_NAME[name]["classification"]]
        return HomuraHimeItem(name, classification, ITEM_BY_NAME[name]["id"], self.player)

    def get_filler_item_name(self) -> str:
        return "Full Heal"  # a real filler item: the currency items count in the logic

    def _vanilla_placements(self) -> Dict[str, str]:
        """
        Location key -> item name for the groups that are not shuffled: each item goes to the first location whose
        base-game reward it is (a location holds one item, so a location that pays a bundle keeps the first item of an
        unshuffled group in it; an item whose locations are all taken stays in the pool). Only as many copies are placed
        as the pool holds.
        """
        item_types = {item_type for option, group in SHUFFLE_GROUPS.items()
                      if not getattr(self.options, option) for item_type in group}
        if not item_types:
            return {}
        by_definition = {i["game"]: i for i in ITEMS if i["type"] in item_types and not i.get("option")}
        remaining = {i["name"]: i["count"] for i in by_definition.values()}
        placed: Dict[str, str] = {}
        for loc in self.active_locations:
            for part in (loc.get("vanilla") or "").split(";"):
                item = by_definition.get(re.sub(r"\s+x\d+$", "", part.strip()))
                if item is not None and remaining[item["name"]] > 0:
                    placed[loc["key"]] = item["name"]
                    remaining[item["name"]] -= 1
                    break
        return placed

    def create_items(self) -> None:
        """
        Builds the item pool: the fixed items of the game, the Konpeito the base game pays at its locations, the
        Senbei, and currency/utility filler for the locations that remain. Groups that are not shuffled are placed
        at their vanilla locations first.
        """
        locked = self._vanilla_placements()
        for key, item_name in locked.items():
            self.get_location(NAME_OF_KEY[key]).place_locked_item(self.create_item(item_name))
        pool: List[str] = []
        for item in ITEMS:
            if item["classification"] == "filler" or item["type"] == "unlock":
                continue
            if item.get("option") == "cut_content" and not self.options.include_cut_content:
                continue
            pool += [item["name"]] * item["count"]
        for item_name in locked.values():
            if item_name in pool:
                pool.remove(item_name)
        if self.options.level_unlock_items == self.options.level_unlock_items.option_freeform_progression:
            pool += [f"{LABEL_OF[world]} Unlock" for world in self.order[1:]]
        elif self.options.level_unlock_items == self.options.level_unlock_items.option_linear_progression:
            pool += [PROGRESSIVE_KEY] * (len(self.order) - 1)  # one more is held from the start: one key per world
        # the Konpeito the vanilla game pays at its locations (the plugin takes those payouts away): one item each
        fixed_konpeito = [loc["konpeito"] for loc in self.active_locations if "konpeito" in loc]
        pool += [f"{amount} Konpeito" for amount in fixed_konpeito]

        # The Dango count is the one large group the player sizes freely, so it gives way when the locations in play (fewer
        # without encounter_clears) cannot hold it, after the Senbei the shops cost and the Sakura Harumi's last reward needs
        # (see _currency_filler). An error here would stop the generation of every player's game, not only this one.
        slots = len(self.active_locations) - len(locked)
        total = self.options.senbei_count.value
        senbei_slots = min(-(-total // 2), SENBEI_PIECES)  # the fewest items that hold the total (single and "2 Senbei")
        sakura_slots = -(-MIN_SAKURA_IN_POOL // COUNTED_SAKURA[SAKURA_ITEMS[-1]])
        room = slots - len(pool) - senbei_slots - sakura_slots
        if room < 0:
            raise OptionError(f"Homura-Hime ({self.player_name}): {len(pool) + senbei_slots + sakura_slots} items for "
                              f"{slots} free locations")
        dango = min(self.options.dango_count.value, room)
        if dango < self.options.dango_count.value:
            logging.warning("Homura-Hime (%s): dango_count lowered from %d to %d, the locations in play have no room for more",
                            self.player_name, self.options.dango_count.value, dango)

        # The traps are sized the same way, after the Dango (the pool's other optional group), one trap after the other.
        traps: Dict[str, int] = {}
        left = room - dango
        for trap, option in TRAP_OPTIONS.items():
            wanted = getattr(self.options, option).value
            traps[trap] = min(wanted, left)
            left -= traps[trap]
            if traps[trap] < wanted:
                logging.warning("Homura-Hime (%s): %s lowered from %d to %d, the locations in play have no room for more",
                                self.player_name, option, wanted, traps[trap])

        def assemble(dango: int, traps: Dict[str, int], heals: int, charges: int, minimum: int, ladder: List[int]) -> Tuple[List[str], int]:
            """The rest of the pool for these choices, and how many Konpeito short of the minimum it is."""
            rest = pool + ["Special Hanami Dango"] * dango + [name for name, count in traps.items() for _ in range(count)]
            free = slots - len(rest)
            # the Senbei total is handed out as single Senbei and, above SENBEI_PIECES, as "2 Senbei" items
            pieces = min(total, SENBEI_PIECES, free - sakura_slots)
            pairs = min(max(0, total - pieces), pieces)
            rest += ["Senbei"] * (pieces - pairs) + ["2 Senbei"] * pairs
            filler, missing = self._currency_filler(free - pieces, sum(fixed_konpeito), minimum, heals, charges, ladder)
            return rest + filler, missing

        minimum = self.options.minimum_konpeito.value
        heals, charges = self.options.full_heal_count.value, self.options.ultimate_charge_count.value
        ladder = KONPEITO_LADDER
        if not self.options.encounter_clears:
            # The fights still pay their Konpeito in the game, the logic just does not count it, and there are about 110
            # fewer places for Konpeito items. So the pool is asked for less, and where that still does not fit the
            # Konpeito target, the rest of the filler gives way, one step at a time (see CLEARS_OFF_STEPS).
            fights = sum(1 for loc in LOCATIONS if loc.get("option") == "encounter_clears")
            minimum = max(0, minimum - CLEARS_OFF_KONPEITO_PER_FIGHT * fights)
            for step, adjust in CLEARS_OFF_STEPS:
                state = self.random.getstate()
                missing = assemble(dango, traps, heals, charges, minimum, ladder)[1]
                self.random.setstate(state)  # a trial: the real pool is built from the same random state
                if missing <= 0:
                    break
                if step == "no_heals":
                    heals = charges = 0
                elif step == "few_dango":
                    dango = min(dango, CLEARS_OFF_DANGO)
                elif step == "few_traps":
                    traps = {name: min(count, CLEARS_OFF_TRAPS) for name, count in traps.items()}
                else:
                    ladder = KONPEITO_BIG_LADDER
                logging.info("Homura-Hime (%s): without encounter clears the Konpeito target needs more room: %s",
                             self.player_name, adjust)
        pool, missing = assemble(dango, traps, heals, charges, minimum, ladder)
        if missing > 0:
            logging.warning("Homura-Hime (%s): the pool has room for about %d fewer Konpeito than minimum_konpeito "
                            "asks for", self.player_name, missing)
        self.options.dango_count.value = dango
        for trap, option in TRAP_OPTIONS.items():
            getattr(self.options, option).value = traps[trap]
        self.senbei_unit = "2 Senbei" if "2 Senbei" in pool else "Senbei"
        self.money_scale = self._scale_currency(pool, KONPEITO_VALUES, COUNTED_KONPEITO)
        self.petal_scale = self._scale_currency(pool, SAKURA_VALUES, COUNTED_SAKURA)
        self.senbei_scale = self._scale_currency(pool, SENBEI_VALUES, self._counted_senbei())
        pool = self._place_local_filler(pool)
        self.multiworld.itempool += [self.create_item(name) for name in pool]
        self._limit_exclusions(pool)

    def _refused_by_shops(self, name: str) -> bool:
        """Whether the shop slots refuse this item of the player's: their own Konpeito, and their dash skills when one is required."""
        return name in KONPEITO_VALUES or (self.dash_required and name in DASH_SKILLS)

    def _place_local_filler(self, pool: List[str]) -> List[str]:
        """
        Local items (local_items) that could never go into a shop slot anyway, and that the logic does not depend on, are put
        into this world's locations right away instead of going through Archipelago's fill. That is this player's own small
        Konpeito pieces: shop slots refuse them (a shop paid for with Konpeito would sell Konpeito), so they can only go to
        the other locations, and the fill can strand them when the free locations left belong to other players or are shops,
        which stops the generation of every player's game. Excluded locations get them first (only filler may go there
        anyway), then the places that are reached last in the play order: these pieces are filler, and the early places are
        the ones the fill needs for the progression items (random places took about 57 of them and starved the first world,
        which stopped the generation for about one seed in eight when every filler item was local). Everything that does fit
        a shop stays in the pool: those items fill the shop slots, and taking them out left the fill with shop slots nothing
        could go into. Items the logic counts (the large Konpeito, Sakura and Senbei pieces) and anything that is progression
        also stay in the pool and the fill. Returns the pool without the placed items.
        """
        local = set()
        for name in self.options.local_items.value:
            local |= self.item_name_groups.get(name, {name})
        # (the shop slots get their item rules in set_rules, after this: what they refuse is stated here, see
        # _apply_location_rules)
        candidates = [name for name in pool if name in local and self._refused_by_shops(name) and not self.create_item(name).advancement]
        if not candidates:
            return pool

        spots = [loc for loc in self.get_locations()
                 if loc.address is not None and loc.item is None and not isinstance(loc, HomuraHimeShopLocation)]
        self.random.shuffle(spots)
        record = {loc["name"]: loc for loc in self.active_locations}
        # excluded ones first, then the latest in the play order first; the shuffle above breaks the ties
        spots.sort(key=lambda loc: (loc.progress_type != LocationProgressType.EXCLUDED, -self._world_index(record[loc.name])))

        remaining = list(pool)
        placed = 0
        for name in candidates:
            item = self.create_item(name)
            spot = next((loc for loc in spots if loc.item_rule(item)), None)
            if spot is None:
                break  # nowhere to put it: the rest goes through the fill as usual
            spots.remove(spot)
            spot.place_locked_item(item)
            remaining.remove(name)
            placed += 1
        if placed:
            logging.info("Homura-Hime (%s): %d local Konpeito pieces placed directly", self.player_name, placed)
        return remaining

    def _limit_exclusions(self, pool: List[str]) -> None:
        """
        Only filler fills an excluded location (the last step of Archipelago's fill), so there cannot be more excluded
        locations than filler items: with few locations in play (no encounter clears) and a low importance of the optional
        ones there could be, and that stops the generation of every player's game. The surplus is not excluded after all.
        """
        fillers = sum(1 for name in pool if self.create_item(name).classification == ItemClassification.filler)
        excluded = [loc for loc in self.get_locations()
                    if loc.address is not None and loc.item is None and loc.progress_type == LocationProgressType.EXCLUDED]
        surplus = len(excluded) - fillers
        if surplus <= 0:
            return
        for location in self.random.sample(excluded, surplus):
            location.progress_type = LocationProgressType.DEFAULT
        logging.warning("Homura-Hime (%s): %d optional locations are not excluded after all, the pool has only %d filler items "
                        "for them", self.player_name, surplus, fillers)

    @staticmethod
    def _scale_currency(pool: List[str], values: Dict[str, int], counted: Dict[str, int]) -> float:
        """All of a currency in the pool per unit of its counted pieces (1 when nothing of it is counted)."""
        total = sum(values.get(name, 0) for name in pool)
        counted_total = sum(counted.get(name, 0) for name in pool)
        return total / counted_total if counted_total else 1.0

    def _currency_filler(self, free: int, fixed_konpeito: int, minimum: int, heals: int, charges: int,
                         ladder: List[int]) -> Tuple[List[str], int]:
        """
        Fills the remaining slots: the Full Heal and Ultimate Charge items, then Sakura Petals and Konpeito. Returns the
        items and how many Konpeito short of `minimum` they are (0 when it is reached).
        - The counted Sakura items hold at least MIN_SAKURA_IN_POOL (Harumi's last reward needs them), taken from
          Konpeito slots.
        - The Konpeito pieces are raised in size until the pool holds at least `minimum` in total (the fixed vanilla
          payouts count towards it); if every piece is at the largest size and it is still short, Sakura slots the
          Harumi minimum can spare and then utility slots turn into Konpeito.
        """
        utility = ["Full Heal"] * heals
        utility += ["Ultimate Charge"] * charges
        slots: List[Optional[str]] = utility[:free]  # None = a Konpeito slot, its size is decided below
        for _ in range(free - len(slots)):
            if self.random.randrange(100) < self.options.filler_sakura_ratio.value:
                slots.append(self.random.choices(SAKURA_ITEMS, SAKURA_WEIGHTS)[0])
            else:
                slots.append(None)

        def sakura() -> int:
            return sum(COUNTED_SAKURA.get(slot, 0) for slot in slots)

        largest_sakura = SAKURA_ITEMS[-1]
        while sakura() < MIN_SAKURA_IN_POOL:
            spare = [i for i, slot in enumerate(slots) if slot is None] or \
                    [i for i, slot in enumerate(slots) if slot not in SAKURA_VALUES] or \
                    [i for i, slot in enumerate(slots) if slot != largest_sakura]
            if not spare:
                raise OptionError(f"Homura-Hime ({self.player_name}): no room for the Sakura Harumi needs")
            slots[self.random.choice(spare)] = largest_sakura

        amounts = {i: KONPEITO_VALUES[self.random.choices(KONPEITO_ITEMS, KONPEITO_WEIGHTS)[0]]
                   for i, slot in enumerate(slots) if slot is None}
        missing = minimum - fixed_konpeito - sum(amounts.values())
        largest = ladder[-1]
        while missing > 0:
            raisable = [i for i, amount in amounts.items() if amount < largest]
            if not raisable:
                # Sakura slots the Harumi minimum can spare go first, the Full Heal / Ultimate Charge counts the player
                # asked for only when nothing else is left
                surplus = sakura() - MIN_SAKURA_IN_POOL
                others = [i for i, slot in enumerate(slots) if COUNTED_SAKURA.get(slot, 0) <= surplus
                          and slot in SAKURA_VALUES] \
                    or [i for i, slot in enumerate(slots) if slot is not None and slot not in SAKURA_VALUES]
                if not others:
                    break  # every slot is a maximal Konpeito piece or needed Sakura: the minimum cannot be reached
                i = self.random.choice(others)
                slots[i], amounts[i] = None, 0
                raisable = [i]
            i = self.random.choice(raisable)
            higher = ladder[ladder.index(amounts[i]) + 1] if amounts[i] else ladder[0]
            missing -= higher - amounts[i]
            amounts[i] = higher
        return [slot if slot is not None else f"{amounts[i]} Konpeito" for i, slot in enumerate(slots)], max(0, missing)

    # ------------------------------------------------------------------ counted items
    def _counted_senbei(self) -> Dict[str, int]:
        """The Senbei item the logic counts (see senbei_unit) and its value."""
        return {self.senbei_unit: SENBEI_VALUES[self.senbei_unit]}

    def _counted(self, name: str) -> Optional[Tuple[str, int]]:
        """The running total an item adds to and by how much, or None when the logic does not count it."""
        if name in self._counted_senbei():
            return SENBEI_COUNTER, SENBEI_VALUES[name]
        return COUNTED.get(name)

    def collect(self, state, item: Item) -> bool:
        """Collecting a counted item also adds its value to the running total it belongs to."""
        changed = super().collect(state, item)
        counted = self._counted(item.name) if changed else None
        if counted:
            state.add_item(counted[0], self.player, counted[1])
        return changed

    def remove(self, state, item: Item) -> bool:
        """The reverse of collect: the value of a counted item leaves its running total."""
        changed = super().remove(state, item)
        counted = self._counted(item.name) if changed else None
        if counted:
            state.remove_item(counted[0], self.player, counted[1])
        return changed

    def _money(self, state) -> int:
        """
        What the player can reasonably have spent by now: MONEY_FACTOR times the Konpeito the randomizer paid out, as
        the counted pieces held stand for it.
        """
        return int(MONEY_FACTOR * self.money_scale * state.count(MONEY_COUNTER, self.player))

    def _senbei(self, state) -> int:
        """
        The Senbei received, as the counted pieces stand for it. Not multiplied by anything: the game has no other
        source of Senbei than the locations, so every Senbei the shops cost has to come from items.
        """
        return int(self.senbei_scale * state.count(SENBEI_COUNTER, self.player))

    def _petals(self, state) -> int:
        """The Sakura the logic counts on: PETALS_PER_CHAPTER for every cleared chapter plus the Sakura items held."""
        return PETALS_PER_CHAPTER * state.count(CLEARED_COUNTER, self.player) + \
            int(self.petal_scale * state.count(PETAL_COUNTER, self.player))

    def _cleared(self, state) -> int:
        """The number of chapters cleared in this state."""
        return state.count(CLEARED_COUNTER, self.player)

    @classmethod
    def stage_finalize_multiworld(cls, multiworld) -> None:
        """
        Once every item is placed and progression balancing is done (it can still move items after post_fill): the
        progression bought in the shops must be affordable by the time it is needed. The repair only moves needed items
        earlier, which is what this stage allows (accessibility may only increase).
        """
        worlds = multiworld.get_game_worlds(GAME_NAME)  # item link groups are not included
        if worlds:
            shop_budget.enforce(multiworld, worlds)

    # ------------------------------------------------------------------ regions
    def create_regions(self) -> None:
        """
        Menu -> Hub -> the sub-chapters of each chapter in story order (chained), plus the finale. Chapter regions are
        entered from the hub; a chapter's first region carries the "Chapter N Entered" event and its last the
        "Chapter N Cleared" event, the finale's last region the "Victory" event.
        """
        menu = Region("Menu", self.player, self.multiworld)
        hub = Region("Hub", self.player, self.multiworld)
        self.multiworld.regions += [menu, hub]
        menu.connect(hub, "Start")

        regions: Dict[str, Region] = {"Hub": hub}
        for chapter in CHAPTERS + [FINALE]:
            for sub in chapter["sub_chapters"]:
                regions[sub["key"]] = Region(sub["key"], self.player, self.multiworld)
                self.multiworld.regions.append(regions[sub["key"]])

        for chapter in CHAPTERS:
            cid = chapter["id"]
            subs = chapter["sub_chapters"]
            hub.connect(regions[subs[0]["key"]], f"Enter {cid}", lambda state, cid=cid: self._can_enter(state, cid))
            for a, b in zip(subs, subs[1:]):
                reqs = TRANSITION_REQ.get(a["key"], [])
                regions[a["key"]].connect(regions[b["key"]], f"{a['key']} -> {b['key']}",
                                          (lambda state, reqs=reqs: self._req(state, reqs)) if reqs else None)
            self._event(regions[subs[0]["key"]], f"{chapter['label']} Entered")
            self._event(regions[subs[-1]["key"]], f"{chapter['label']} Cleared")

        finale = FINALE["sub_chapters"]
        hub.connect(regions[finale[0]["key"]], "Enter Finale",
                    lambda state: self._cleared(state) >= len(NUMBERED_CHAPTERS) and state.has("Climax Cleared", self.player))
        for a, b in zip(finale, finale[1:]):
            regions[a["key"]].connect(regions[b["key"]], f"{a['key']} -> {b['key']}")
        self._event(regions[finale[-1]["key"]], "Victory")

        for loc in self.active_locations:
            region = regions[loc["region"]]
            if loc["category"] == "shop":
                location = HomuraHimeShopLocation(self.player, loc["name"], loc["id"], region)
                location.price, location.senbei = SHOP_PRICES[loc["key"]], SHOP_SENBEI[loc["key"]]
                self.shop_slots.append(location)
            else:
                location = HomuraHimeLocation(self.player, loc["name"], loc["id"], region)
            region.locations.append(location)
            self._apply_optional_importance(location, loc)

    def _event(self, region: Region, name: str) -> None:
        """Adds a locked event item with a matching event location to a region (the logic's progress markers)."""
        location = HomuraHimeLocation(self.player, name, None, region)
        region.locations.append(location)
        location.place_locked_item(HomuraHimeItem(name, ItemClassification.progression, None, self.player))

    def _apply_optional_importance(self, location: HomuraHimeLocation, loc: dict) -> None:
        """Optional content (ambushes, trials, head chases, Ikai rooms) hides important items less often: only a share
        of those locations may hold progression or useful items, the rest are excluded from them."""
        if loc["category"] not in OPTIONAL_CATEGORIES and not loc.get("optional"):
            return
        if self.random.randrange(100) >= self.options.optional_location_importance.value:
            location.progress_type = LocationProgressType.EXCLUDED

    # ------------------------------------------------------------------ rules
    def _req(self, state, reqs: List[str]) -> bool:
        """Whether the state has every requirement; "dash" stands for any dash skill (see SCENE_REQ)."""
        for r in reqs:
            if r == "dash":
                if self.dash_required and not state.has_any(DASH_SKILLS, self.player):
                    return False
            elif not state.has(r, self.player):
                return False
        return True

    def _can_enter(self, state, chapter_id: str) -> bool:
        """
        Whether a chapter can be entered from the hub: in play order the previous chapter must be cleared (except with
        randomized order and unlock items, where the unlock item alone opens a chapter), and with unlock items the
        chapter's own unlock item is needed.
        """
        slot = self.order.index(chapter_id)
        keys = self.options.level_unlock_items
        freeform = keys == keys.option_freeform_progression
        # in play order the previous world must be beaten (not with freeform keys: the key alone opens a world)
        if slot > 0 and not freeform and not state.has(f"{LABEL_OF[self.order[slot - 1]]} Cleared", self.player):
            return False
        if freeform and not state.has(f"{LABEL_OF[chapter_id]} Unlock", self.player):
            return False
        # progressive keys: the key count of the world's place in the order
        if keys == keys.option_linear_progression and state.count(PROGRESSIVE_KEY, self.player) < slot + 1:
            return False
        # the climax is never the first world, whatever order the unlock items allow
        if chapter_id == CLIMAX_ID and self._cleared(state) < 1:
            return False
        return True

    def set_rules(self) -> None:
        """Applies the access rule of every location and the completion condition (the finale's Victory event)."""
        # freeform keys: the place of each key's world in the play order ("Chapter 3 Unlock" -> 4)
        if self.options.level_unlock_items == self.options.level_unlock_items.option_freeform_progression:
            self.key_position = {f"{LABEL_OF[world]} Unlock": position for position, world in enumerate(self.order)}
        for loc in self.active_locations:
            self._apply_location_rules(self.get_location(loc["name"]), loc)
        self.multiworld.completion_condition[self.player] = lambda state: state.has("Victory", self.player)

    def _apply_location_rules(self, location: Location, loc: dict) -> None:
        """The access rule and item rules of one location, built from its category and the requirement tables."""
        reqs: List[str] = list(loc["scene_req"] if "scene_req" in loc else SCENE_REQ.get(loc.get("scene", ""), []))
        category = loc["category"]
        rule: Optional[Callable] = None
        if category == "shop":
            # the tier of the slot in cleared chapters, and the price in Konpeito and Senbei
            tier, price, senbei = max(loc["tier"], SHOP_MIN_CLEARED), loc["price"], loc["senbei"]
            rule = lambda state, tier=tier, price=price, senbei=senbei: \
                self._cleared(state) >= tier and self._money(state) >= price and self._senbei(state) >= senbei
            if self.dash_required:
                # a dash skill is needed early in Level 1; shop prices (8000+ Konpeito) would make that a grind
                add_item_rule(location, lambda item: not (item.player == self.player and item.name in DASH_SKILLS))
            # the shop is paid for with Konpeito, so selling it there is a wasted purchase (Senbei may be sold: they are
            # scarce, and the budget check counts them when they sit in a slot)
            add_item_rule(location, lambda item: not (item.player == self.player and item.name in KONPEITO_VALUES))
        elif category == "stage_clear":
            label = LABEL_OF[loc["chapter"]]
            rule = lambda state, label=label: state.has(f"{label} Cleared", self.player)
        elif category == "harumi":
            rule = lambda state, need=loc["petals"]: \
                self._cleared(state) >= HARUMI_MIN_CLEARED and self._petals(state) >= need
        elif loc["key"] in HUB_CLEARS_REQUIRED:
            rule = lambda state, clears=HUB_CLEARS_REQUIRED[loc["key"]]: self._cleared(state) >= clears
        elif category == "stall":
            reqs.append("Inugami Certificate")
        if reqs:
            base = rule
            rule = lambda state, reqs=reqs, base=base: self._req(state, reqs) and (base is None or base(state))
        if rule is not None:
            set_rule(location, rule)

        # gate items may not go where we cannot yet tell front from behind the gate
        scene = loc.get("scene")
        for item_name, (gate_scene, safe_key) in GATE_PLACEMENT_LIMIT.items():
            if scene == gate_scene and loc["key"] != safe_key:
                add_item_rule(location, lambda item, item_name=item_name:
                              not (item.player == self.player and item.name == item_name))

        if self.options.level_unlock_items == self.options.level_unlock_items.option_freeform_progression:
            self._keys_follow_the_order(location, loc)

    def _world_index(self, loc: dict) -> int:
        """
        How far into the play order a location of this world is reached: the index of the world it is in, or for a place in
        the hub the index of the world whose clear opens it (a stage-clear reward, a shop slot by its tier), else 0.
        """
        chapter = CHAPTER_OF_REGION.get(loc["region"])
        if chapter is not None:
            return len(self.order) if chapter == FINALE["id"] else self.order.index(chapter)
        if loc["category"] == "stage_clear":
            return self.order.index(loc["chapter"])
        if loc["category"] == "shop":
            return min(max(loc["tier"], SHOP_MIN_CLEARED) - 1, len(self.order) - 1)
        return 0

    def _keys_follow_the_order(self, location: Location, loc: dict) -> None:
        """
        Freeform level keys: the order of the worlds is also the order the keys turn up in. The key of a world may only lie
        in a world that comes before it (or in the hub where an earlier world's clear leads), never in its own world or a
        later one; keys sent to another player's world are not limited.
        """
        index, position = self._world_index(loc), self.key_position
        add_item_rule(location, lambda item: not (item.player == self.player and item.name in position
                                                  and position[item.name] <= index))

    # ------------------------------------------------------------------ slot data
    def fill_slot_data(self) -> Dict[str, Any]:
        """What the plugin (and Universal Tracker) need to know about this slot beyond the item and location tables."""
        return {
            "world_version": self.world_version.as_simple_string(),
            "level_order": self.order,
            "level_order_mode": self.options.level_order.current_key,
            "level_unlock_items": self.options.level_unlock_items.current_key,
            "dango_count": self.options.dango_count.value,
            **{option: getattr(self.options, option).value for option in TRAP_OPTIONS.values()},
            **{name: bool(getattr(self.options, name)) for name in SLOT_DATA_TOGGLES},
        }
