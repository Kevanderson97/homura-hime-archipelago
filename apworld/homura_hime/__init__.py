CURRENCY_NAMES = set(KONPEITO_VALUES) | set(SAKURA_VALUES) | set(SENBEI_VALUES)


class HomuraHimeItem(Item):
    """An item of this game (also used for the event items of the regions, which have no id)."""
    game = GAME_NAME

    @property
    def flags(self) -> int:
        """
        What the server tells clients about the item. Konpeito and Sakura count as progression while the multiworld is
        generated (the shop and Harumi logic count them), but are no progression for the players: they are announced as
        plain filler.
        """
        return 0 if self.name in CURRENCY_NAMES else super().flags


class HomuraHimeLocation(Location):
    """A location of this game."""
    game = GAME_NAME


class HomuraHimeShopLocation(HomuraHimeLocation):
    """A shop slot: its prices decide when it is reachable (HomuraHimeWorld._money), see also shop_budget.py."""
    price: int = 0  # Konpeito
    senbei: int = 0


